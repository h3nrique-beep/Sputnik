export const title = (v: string) =>
  v === "dashboard"
    ? "Visão geral"
    : v === "movement"
      ? "Movimentar estoque"
      : v === "schedule"
        ? "Agenda"
        : v === "finance"
          ? "Financeiro operacional"
          : v === "report"
            ? "Relatório mensal"
            : v === "reposition"
              ? "Reposição"
              : v === "users"
                ? "Usuários"
                : v === "subscription"
                  ? "Assinatura"
                  : v === "developer"
                    ? "Desenvolvedor"
                    : v.startsWith("pieces")
                      ? v === "pieces-new"
                        ? "Cadastrar peça"
                        : "Peças"
                      : v.startsWith("clients")
                        ? v === "clients-new"
                          ? "Cadastrar cliente"
                          : "Clientes"
                        : v.startsWith("vehicles")
                          ? v === "vehicles-new"
                            ? "Cadastrar veículo"
                            : "Veículos"
                          : v === "quotes-new"
                            ? "Novo orçamento"
                            : v === "orders-new"
                              ? "Nova ordem de serviço"
                              : v.startsWith("order-")
                                ? "Detalhes da OS"
                                : "Ordens de serviço";

export const subtitle = (v: string) =>
  v === "dashboard"
    ? "Controle operacional da sua oficina"
    : v === "quotes-new"
      ? "Monte a proposta; o estoque só muda após a aprovação do cliente"
      : v === "schedule"
        ? "Próximos atendimentos da oficina"
        : v === "finance"
          ? "Valores previstos e concluídos nas ordens de serviço"
          : v === "orders-new"
            ? "Selecione o cliente e o veículo para registrar o atendimento"
            : v === "developer"
              ? "Monitoramento, manutenção e cópias seguras do sistema"
              : "Gestão simples, segura e organizada";
