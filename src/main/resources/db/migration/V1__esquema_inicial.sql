-- Esquema inicial do Sputnik no PostgreSQL, equivalente ao mapeamento JPA atual.
-- Mudanças futuras entram em novos arquivos V2__..., V3__...; nunca edite este.

create table cliente (
    empresa_id bigint,
    id bigint generated by default as identity,
    cpf varchar(255) not null,
    nome varchar(255) not null,
    telefone varchar(255) not null,
    primary key (id)
);

create table empresas (
    periodo_teste_ate date,
    id bigint generated by default as identity,
    documento varchar(30),
    slug varchar(60) not null,
    nome varchar(120) not null,
    plano varchar(255) not null check (plano in ('STARTER','PROFISSIONAL','PREMIUM')),
    status_assinatura varchar(255) not null check (status_assinatura in ('ATIVA','EM_TESTE','SUSPENSA','CANCELADA')),
    primary key (id),
    unique (slug)
);

create table historico_ordem_servico (
    data timestamp(6) not null,
    id bigint generated by default as identity,
    ordem_servico_id bigint not null,
    descricao varchar(500) not null,
    responsavel varchar(255) not null,
    primary key (id)
);

create table item_ordem_servico (
    estoque_baixado boolean not null,
    quantidade integer not null,
    valor_unitario numeric(12,2) not null,
    id bigint generated by default as identity,
    ordem_servico_id bigint not null,
    peca_id bigint,
    descricao varchar(255) not null,
    tipo varchar(255) not null check (tipo in ('PECA','SERVICO')),
    primary key (id)
);

create table lancamento_financeiro (
    pagamento_em date,
    valor numeric(14,2) not null,
    vencimento date not null,
    criado_em timestamp(6) not null,
    empresa_id bigint,
    id bigint generated by default as identity,
    ordem_servico_id bigint,
    categoria varchar(80),
    descricao varchar(160) not null,
    status varchar(255) not null check (status in ('PENDENTE','PAGO')),
    tipo varchar(255) not null check (tipo in ('RECEITA','DESPESA')),
    primary key (id)
);

create table movimentacao (
    quantidade integer not null,
    saldo_resultante integer not null,
    data timestamp(6) not null,
    empresa_id bigint,
    id bigint generated by default as identity,
    peca_id bigint not null,
    observacao varchar(255),
    operador varchar(255) not null,
    tipo varchar(255) not null check (tipo in ('ENTRADA','SAIDA')),
    primary key (id)
);

create table ordem_servico (
    ano_modelo integer,
    combustivel_percentual integer,
    garantia_ate date,
    quilometragem_abertura integer,
    retorno_em date,
    validade_dias integer,
    abertura timestamp(6) not null,
    agendamento timestamp(6),
    cliente_id bigint not null,
    empresa_id bigint,
    id bigint generated by default as identity,
    previsao_entrega timestamp(6),
    previsao_orcamento timestamp(6),
    retirada_em timestamp(6),
    ultima_atualizacao timestamp(6),
    veiculo_id bigint not null,
    descricao varchar(1200),
    observacoes varchar(1200),
    certificado_garantia varchar(255),
    condicao_pagamento varchar(255),
    consultor_tecnico varchar(255),
    cor varchar(255),
    motor varchar(255),
    oficina_contato varchar(255),
    oficina_documento varchar(255),
    oficina_endereco varchar(255),
    oficina_nome varchar(255),
    pagador_documento varchar(255),
    pagador_email varchar(255),
    pagador_endereco varchar(255),
    pagador_nome varchar(255),
    pagador_telefone varchar(255),
    prisma varchar(255),
    proprietario_email varchar(255),
    proprietario_endereco varchar(255),
    reembolso varchar(255),
    status varchar(255) not null,
    tipo_servico varchar(255),
    primary key (id)
);

create table pecas (
    estoque_disponivel integer check (estoque_disponivel>=0),
    estoque_minimo integer not null check (estoque_minimo>=0),
    preco numeric(38,2) not null,
    saldo integer not null check (saldo>=0),
    empresa_id bigint,
    id bigint generated by default as identity,
    categoria varchar(255) not null,
    codigo varchar(255) not null unique,
    fabricante varchar(255) not null,
    fornecedor varchar(255) not null,
    localizacao varchar(255) not null,
    nome varchar(255) not null,
    primary key (id)
);

create table usuario_permissoes (
    usuario_id bigint not null,
    permissao varchar(255) not null check (permissao in ('PECAS','ORDENS','FINANCEIRO','RELATORIO_MENSAL','REPOSICAO')),
    primary key (usuario_id, permissao)
);

create table usuarios_sistema (
    troca_senha_obrigatoria boolean default false not null,
    empresa_id bigint,
    id bigint generated by default as identity,
    email varchar(255) unique,
    nome varchar(255) not null,
    perfil varchar(255) not null check (perfil in ('BALCONISTA','ADMIN')),
    senha_hash varchar(255) not null,
    usuario varchar(255) not null unique,
    primary key (id)
);

create table veiculo (
    ano integer,
    quilometragem_atual integer,
    cliente_id bigint,
    empresa_id bigint,
    id bigint generated by default as identity,
    chassi varchar(255) not null unique,
    marca_modelo varchar(255) not null,
    placa varchar(255) not null,
    primary key (id)
);

alter table historico_ordem_servico
    add constraint fk_historico_ordem_servico_ordem_servico
    foreign key (ordem_servico_id) references ordem_servico;

alter table item_ordem_servico
    add constraint fk_item_ordem_servico_ordem_servico
    foreign key (ordem_servico_id) references ordem_servico;

alter table item_ordem_servico
    add constraint fk_item_ordem_servico_peca
    foreign key (peca_id) references pecas;

alter table lancamento_financeiro
    add constraint fk_lancamento_financeiro_ordem_servico
    foreign key (ordem_servico_id) references ordem_servico;

alter table movimentacao
    add constraint fk_movimentacao_peca
    foreign key (peca_id) references pecas;

alter table ordem_servico
    add constraint fk_ordem_servico_cliente
    foreign key (cliente_id) references cliente;

alter table ordem_servico
    add constraint fk_ordem_servico_veiculo
    foreign key (veiculo_id) references veiculo;

alter table usuario_permissoes
    add constraint fk_usuario_permissoes_usuario
    foreign key (usuario_id) references usuarios_sistema;

alter table usuarios_sistema
    add constraint fk_usuarios_sistema_empresa
    foreign key (empresa_id) references empresas;

alter table veiculo
    add constraint fk_veiculo_cliente
    foreign key (cliente_id) references cliente;

-- empresa_id é filtrado em toda consulta da sessão (filtro Hibernate empresaAtual).
create index ix_cliente_empresa_id on cliente (empresa_id);
create index ix_veiculo_empresa_id on veiculo (empresa_id);
create index ix_veiculo_cliente_id on veiculo (cliente_id);
create index ix_pecas_empresa_id on pecas (empresa_id);
create index ix_movimentacao_empresa_id on movimentacao (empresa_id);
create index ix_movimentacao_peca_id on movimentacao (peca_id);
create index ix_ordem_servico_empresa_id on ordem_servico (empresa_id);
create index ix_ordem_servico_cliente_id on ordem_servico (cliente_id);
create index ix_ordem_servico_veiculo_id on ordem_servico (veiculo_id);
create index ix_ordem_servico_status on ordem_servico (status);
create index ix_item_ordem_servico_ordem_servico_id on item_ordem_servico (ordem_servico_id);
create index ix_historico_ordem_servico_ordem_servico_id on historico_ordem_servico (ordem_servico_id);
create index ix_lancamento_financeiro_empresa_id on lancamento_financeiro (empresa_id);
create index ix_lancamento_financeiro_vencimento on lancamento_financeiro (vencimento);
create index ix_usuarios_sistema_empresa_id on usuarios_sistema (empresa_id);
